"""Generates the standalone PipeWire client config that runs the microphone filter.

The service starts `pipewire -c <absolute path>` with this file: a small client
(same base modules as /usr/share/pipewire/filter-chain.conf) that loads one
filter-chain. Verified on PipeWire 1.6.11.
"""

import json

from . import CHANNEL, HIGHPASS, PRIORITY, VIRTUAL_SOURCE


def _q(s: str) -> str:
    # PipeWire config is SPA-JSON, so a JSON string literal is a valid value.
    return json.dumps(s, ensure_ascii=False)


def build_conf(physical_source: str, rnnoise_plugin: str | None, description: str) -> str:
    # Stages in signal order: (node definition, input port, output port).
    stages = [
        (
            f'type = builtin name = hp{i} label = bq_highpass control = {{ "Freq" = {f} "Q" = {q} }}',
            f"hp{i}:In",
            f"hp{i}:Out",
        )
        for i, (f, q) in enumerate(HIGHPASS, start=1)
    ]
    if rnnoise_plugin:
        stages.append(
            (
                f"type = ladspa name = rnnoise plugin = {_q(rnnoise_plugin)} label = noise_suppressor_mono",
                "rnnoise:Input",
                "rnnoise:Output",
            )
        )
    node_lines = "\n".join(f"          {{ {node} }}" for node, _, _ in stages)
    link_lines = " ".join(
        f'{{ output = "{a[2]}" input = "{b[1]}" }}' for a, b in zip(stages, stages[1:], strict=False)
    )
    desc = _q(description)
    return f"""# Generated by GF63 Mic Fix. Do not edit: the app rewrites this file.
context.properties = {{
    log.level = 0
}}
context.spa-libs = {{
    audio.convert.* = audioconvert/libspa-audioconvert
    support.*       = support/libspa-support
}}
context.modules = [
    {{ name = libpipewire-module-rt args = {{ }} flags = [ ifexists nofail ] }}
    {{ name = libpipewire-module-protocol-native }}
    {{ name = libpipewire-module-client-node }}
    {{ name = libpipewire-module-adapter }}
    {{ name = libpipewire-module-filter-chain
      args = {{
        node.description = {desc}
        media.name = {desc}
        filter.graph = {{
          nodes = [
{node_lines}
          ]
          links = [ {link_lines} ]
          inputs = [ "{stages[0][1]}" ]
          outputs = [ "{stages[-1][2]}" ]
        }}
        capture.props = {{
          node.name = {_q("capture." + VIRTUAL_SOURCE)}
          target.object = {_q(physical_source)}
          audio.channels = 1
          audio.position = [ {CHANNEL} ]
          stream.dont-remix = true
          node.passive = true
        }}
        playback.props = {{
          node.name = {_q(VIRTUAL_SOURCE)}
          media.class = Audio/Source
          audio.channels = 1
          audio.position = [ MONO ]
          priority.session = {PRIORITY}
          priority.driver = {PRIORITY}
        }}
      }}
    }}
]
"""
